const assert=require('node:assert/strict');
const core=require('../take-profit-core.js');
const policy=core.defaultPolicy('2026-09-21','2026-09-21T10:00:00+08:00');
assert.equal(core.validatePolicy(policy,'2026-09-21'),true);
const stage=(date,rate,cal='2026-09-21')=>core.deriveStage({startDate:'2023-09-21',asOfDate:date,formalXirr:rate,calibrationDate:cal,policy});
assert.equal(stage('2026-09-20',0.16).stage,'AHEAD_NO_TAKE_PROFIT');
assert.equal(stage('2026-09-21',0.09).stage,'TAKE_PROFIT_WATCH');
assert.equal(stage('2026-09-21',0.0599).stage,'ACCUMULATE');
assert.equal(stage('2026-09-21',0.06).stage,'AHEAD_NO_TAKE_PROFIT');
assert.equal(stage('2026-09-21',0.08).stage,'TAKE_PROFIT_WATCH');
assert.equal(stage('2026-09-21',0.10).stage,'TAKE_PROFIT_PARTIAL');
assert.equal(stage('2026-09-21',0.12).stage,'TAKE_PROFIT_HIGHER_LOCK');
assert.equal(stage('2026-09-21',0.15).stage,'TAKE_PROFIT_STRONG_LOCK');
assert.equal(stage('2028-09-20',0.15).stage,'TAKE_PROFIT_STRONG_LOCK');
assert.equal(stage('2028-09-21',0.07,'2028-09-21').stage,'EXIT_DE_RISK');
assert.equal(stage('2028-09-21',0.04,'2028-09-21').stage,'REASSESS_STRATEGY');
assert.equal(stage('2028-09-21',null).stage,'DATA_UNAVAILABLE');
assert.equal(stage('2028-09-21',0.08,'2028-08-01').stage,'DATA_UNAVAILABLE');
assert.equal(stage('2026-09-21',null).stage,'DATA_UNAVAILABLE');
assert.equal(stage('2026-09-21',0.11,'2026-09-06').freshness,'STALE');
assert.equal(stage('2026-09-21',0.11,'2026-09-14').freshness,'FRESH');
assert.equal(stage('2026-09-21',0.11,'2026-09-13').freshness,'AGING');
assert.equal(stage('2026-09-21',0.11,'2026-09-07').freshness,'AGING');
const s=stage('2026-09-21',0.11);
const baseline=core.baselineCandidate({existing:null,stage:s,calibration:{id:'cal-test',fundMarketValueCent:2000000},formalXirr:0.11,asOfDate:'2026-09-21',policy});
assert.equal(baseline.baseMarketValueCent,2000000);
assert.equal(core.baselineCandidate({existing:baseline,stage:s,calibration:{id:'later',fundMarketValueCent:3000000},formalXirr:0.12,asOfDate:'2026-09-21',policy}),null);
assert.equal(core.baselineCandidate({existing:null,stage:stage('2026-09-21',0.11,'2026-09-06'),calibration:{id:'stale',fundMarketValueCent:3000000},formalXirr:0.11,asOfDate:'2026-09-21',policy}),null);
const event={settlementStatus:'SETTLED',grossRedemptionAmountCent:200000,netCashReceivedCent:199000,principalReleasedCent:150000};
const progress=core.progress([event,{settlementStatus:'PENDING_SETTLEMENT',grossRedemptionAmountCent:100000}],baseline,s.band);
assert.equal(progress.ratio,0.1);
assert.equal(progress.toLowerCent,0);
assert.equal(progress.toUpperCent,200000);
assert.equal(progress.realizedProfitCent,49000);
assert.deepEqual(core.previewSettlement({grossCent:200000,feeCent:1000,netCent:199000,marketValueCent:2000000,principalCent:1500000}),{grossCent:200000,feeCent:1000,netCent:199000,ratio:0.1,principalReleasedCent:150000,postPrincipalCent:1350000,realizedProfitCent:49000,cashIncreaseCent:199000,externalCashflowCent:0});
assert.throws(()=>core.previewSettlement({grossCent:200000,feeCent:1000,netCent:200000,marketValueCent:2000000,principalCent:1500000}),/INVALID_SETTLEMENT/);
assert.deepEqual(core.completeAmounts({grossCent:200000,feeCent:1000,netCent:null}),{grossCent:200000,feeCent:1000,netCent:199000,complete:true});
assert.deepEqual(core.completeAmounts({grossCent:null,feeCent:1000,netCent:199000}),{grossCent:200000,feeCent:1000,netCent:199000,complete:true});
assert.equal(core.completeAmounts({grossCent:200000,feeCent:null,netCent:199000}).complete,false);
assert.throws(()=>core.completeAmounts({grossCent:200000,feeCent:1000,netCent:200000}),/INVALID_SETTLEMENT/);
assert.equal(core.isOverride(100000,baseline,s.band,0),true);
assert.equal(core.isOverride(200000,baseline,s.band,0),false);
assert.equal(core.isOverride(500000,baseline,s.band,0),true);
const future={...policy,id:'tp-policy-v2',effectiveFrom:'2026-10-01',reason:'调整',bands:policy.bands.map(x=>({...x}))};
assert.equal(core.effectivePolicy([policy,future],'2026-09-30').id,'tp-policy-v1');
assert.equal(core.effectivePolicy([policy,future],'2026-10-01').id,'tp-policy-v2');
assert.throws(()=>core.validatePolicy({...future,effectiveFrom:'2026-09-20'},'2026-09-21'),/POLICY_RETROACTIVE/);
assert.throws(()=>core.validatePolicy({...future,bands:[...future.bands.slice(0,1),{...future.bands[1],minXirr:0.11},future.bands[2]]},'2026-09-21'),/XIRR_BANDS_GAP/);
assert.throws(()=>core.validatePolicy({...future,bands:[{...future.bands[0],targetMin:0.6,targetMax:0.2},...future.bands.slice(1)]},'2026-09-21'),/INVALID_TARGET_RATIO/);
assert.equal(core.previewSettlement({grossCent:2000000,feeCent:0,netCent:2000000,marketValueCent:2000000,principalCent:1500000}).postPrincipalCent,0);
assert.throws(()=>core.previewSettlement({grossCent:2000001,feeCent:0,netCent:2000001,marketValueCent:2000000,principalCent:1500000}),/INVALID_SETTLEMENT/);
assert.throws(()=>core.previewSettlement({grossCent:1,feeCent:0,netCent:1,marketValueCent:0,principalCent:1500000}),/INVALID_SETTLEMENT/);
console.log('take-profit-core: tests passed');
